create or replace TRANSIENT TABLE ENG_STAGING.BRANDT_REPORT_DM.FACT_INVOICE (
	INVOICEKEY NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder COMMENT 'Surrogate key',
	INVOICEID NUMBER(38,0) NOT NULL COMMENT 'Natural key from source system',
	JOBID NUMBER(38,0) NOT NULL,
	TENANTID NUMBER(38,0) NOT NULL,
	DATEKEY NUMBER(38,0),
	CUSTOMERKEY NUMBER(38,0),
	LOCATIONKEY NUMBER(38,0),
	BUSINESSUNITKEY NUMBER(38,0),
	JOBTYPEKEY NUMBER(38,0),
	EMPLOYEEKEY NUMBER(38,0),
	JOBKEY NUMBER(38,0),
	INVOICEDON DATE,
	POSTEDDATE DATE,
	INVOICEDATE DATE,
	TRANSACTIONNUMBER VARCHAR(50),
	INVOICESTATUS NUMBER(38,0),
	ISADJUSTMENT BOOLEAN,
	ADJUSTMENTTOINVOICEID NUMBER(38,0),
	TOTALREVENUE NUMBER(20,2),
	INCOMEREVENUE NUMBER(20,2) COMMENT 'Revenue from income GL accounts only (for job revenue calculation)',
	LINEITEMCOUNT NUMBER(38,0),
	EQUIPMENTCOST NUMBER(20,2),
	MATERIALCOST NUMBER(20,2),
	TOTALITEMCOST NUMBER(20,2),
	POUNBILLEDCOST NUMBER(20,2),
	POBILLEDCOST NUMBER(20,2),
	TOTALPOCOST NUMBER(20,2),
	POCOUNT NUMBER(38,0),
	REGULARLABORCOST NUMBER(20,2),
	PIECEWORKCOST NUMBER(20,2),
	LABORBURDENCOST NUMBER(20,2),
	PAYROLLADJUSTMENTCOST NUMBER(20,2),
	TOTALLABORCOST NUMBER(20,2) COMMENT 'Regular + Piecework + Burden + Adjustments (pre-summed from Mat_Invoice_LaborCosts)',
	REGULARLABORHOURS NUMBER(20,2),
	PIECEWORKHOURS NUMBER(20,2),
	LOADDATETIME TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	UPDATEDDATETIME TIMESTAMP_NTZ(9),
	unique (INVOICEID),
	primary key (INVOICEKEY)
)COMMENT='Invoice-level fact with denormalized base measures from Layer 1'
;



