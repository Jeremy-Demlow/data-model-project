create or replace TRANSIENT TABLE ENG_STAGING.BRANDT_REPORT_DM.FACT_SERVICEAGREEMENT (
	SERVICEAGREEMENTKEY NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder COMMENT 'Surrogate key for this fact',
	SERVICEAGREEMENTID NUMBER(38,0) NOT NULL COMMENT 'Natural key from source system',
	PERIODSTARTDATE DATE NOT NULL COMMENT 'Start date of reporting period (from ETL parameters)',
	PERIODENDDATE DATE NOT NULL COMMENT 'End date of reporting period (from ETL parameters)',
	TENANTID NUMBER(38,0) NOT NULL,
	DATEKEY NUMBER(38,0),
	CUSTOMERKEY NUMBER(38,0),
	LOCATIONKEY NUMBER(38,0),
	BUSINESSUNITKEY NUMBER(38,0),
	EMPLOYEEKEY NUMBER(38,0),
	SERVICEAGREEMENTDIMKEY NUMBER(38,0),
	SANAME VARCHAR(500),
	SATEMPLATETYPE VARCHAR(250),
	SASTARTDATE DATE,
	SAENDDATE DATE,
	SARENEWALYEAR NUMBER(38,0) COMMENT 'Renewal year (1, 2, 3+) based on renewal chain',
	SASTATUS NUMBER(38,0),
	REVENUERECOGNITIONAMOUNT NUMBER(20,2) COMMENT 'Revenue recognized via journal entries in this period',
	LABORCOST NUMBER(20,2) COMMENT 'Direct labor costs from SA visit jobs',
	BURDENCOST NUMBER(20,2) COMMENT 'Labor burden costs from SA visit jobs',
	MATERIALCOST NUMBER(20,2),
	EQUIPMENTCOST NUMBER(20,2),
	SOLDBYEMPLOYEEID NUMBER(38,0) COMMENT 'Employee who sold the SA (for commission calculation)',
	JOBCOMMISSIONPCT NUMBER(10,2),
	SAYEAR1COMMISSIONPCT NUMBER(10,2),
	SAYEAR2COMMISSIONPCT NUMBER(10,2),
	SAYEAR3PLUSCOMMISSIONPCT NUMBER(10,2),
	LOADDATETIME TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	UPDATEDDATETIME TIMESTAMP_NTZ(9),
	unique (SERVICEAGREEMENTID, PERIODSTARTDATE, PERIODENDDATE, TENANTID),
	primary key (SERVICEAGREEMENTKEY)
)COMMENT='Service agreement periodic fact with revenue recognition and visit job costs'
;
